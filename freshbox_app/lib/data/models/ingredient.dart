import 'package:flutter/material.dart';

enum IngredientCategory {
  meat('肉類', '🥩'),
  vegetable('野菜', '🥬'),
  fish('魚介', '🐟'),
  dairy('乳製品', '🥛'),
  seasoning('調味料', '🧂'),
  frozen('冷凍', '❄️'),
  other('その他', '📦');

  const IngredientCategory(this.label, this.emoji);
  final String label;
  final String emoji;

  static IngredientCategory fromLabel(String label) {
    return IngredientCategory.values.firstWhere(
      (e) => e.label == label,
      orElse: () => IngredientCategory.other,
    );
  }
}

enum StorageLocation {
  refrigerator('冷蔵庫', '❄️'),
  freezer('冷凍庫', '🧊'),
  pantry('パントリー/常温棚', '📦'),
  snackShelf('お菓子棚', '🍪');

  const StorageLocation(this.label, this.emoji);
  final String label;
  final String emoji;

  static StorageLocation fromLabel(String label) {
    return StorageLocation.values.firstWhere(
      (e) => e.label == label,
      orElse: () => StorageLocation.refrigerator,
    );
  }
}

class Ingredient {
  final String id;
  final String name;
  final IngredientCategory category;
  final double quantity;
  final String unit;
  final DateTime expiryDate;
  final DateTime? purchasedDate;
  final String? memo;
  final StorageLocation storageLocation;
  final int? price;

  const Ingredient({
    required this.id,
    required this.name,
    required this.category,
    required this.quantity,
    required this.unit,
    required this.expiryDate,
    this.purchasedDate,
    this.memo,
    this.storageLocation = StorageLocation.refrigerator,
    this.price,
  });

  int get daysUntilExpiry {
    final now = DateTime.now();
    final today = DateTime(now.year, now.month, now.day);
    final expiry = DateTime(expiryDate.year, expiryDate.month, expiryDate.day);
    return expiry.difference(today).inDays;
  }

  Ingredient copyWith({
    String? id,
    String? name,
    IngredientCategory? category,
    double? quantity,
    String? unit,
    DateTime? expiryDate,
    DateTime? purchasedDate,
    String? memo,
    StorageLocation? storageLocation,
    int? price,
  }) {
    return Ingredient(
      id: id ?? this.id,
      name: name ?? this.name,
      category: category ?? this.category,
      quantity: quantity ?? this.quantity,
      unit: unit ?? this.unit,
      expiryDate: expiryDate ?? this.expiryDate,
      purchasedDate: purchasedDate ?? this.purchasedDate,
      memo: memo ?? this.memo,
      storageLocation: storageLocation ?? this.storageLocation,
      price: price ?? this.price,
    );
  }

  // Hive用: Map変換
  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'name': name,
      'category': category.label,
      'quantity': quantity,
      'unit': unit,
      'expiryDate': expiryDate.millisecondsSinceEpoch,
      'purchasedDate': purchasedDate?.millisecondsSinceEpoch,
      'memo': memo,
      'storageLocation': storageLocation.label,
      'price': price,
    };
  }

  factory Ingredient.fromMap(Map<dynamic, dynamic> map) {
    return Ingredient(
      id: map['id'] as String,
      name: map['name'] as String,
      category: IngredientCategory.fromLabel(map['category'] as String),
      quantity: (map['quantity'] as num).toDouble(),
      unit: map['unit'] as String,
      expiryDate: DateTime.fromMillisecondsSinceEpoch(map['expiryDate'] as int),
      purchasedDate: map['purchasedDate'] != null
          ? DateTime.fromMillisecondsSinceEpoch(map['purchasedDate'] as int)
          : null,
      memo: map['memo'] as String?,
      storageLocation: map['storageLocation'] != null
          ? StorageLocation.fromLabel(map['storageLocation'] as String)
          : StorageLocation.refrigerator,
      price: map['price'] as int?,
    );
  }

